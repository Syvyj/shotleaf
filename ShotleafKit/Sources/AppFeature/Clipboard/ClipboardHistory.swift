import AppKit
import Core
import UniformTypeIdentifiers

/// One thing that was copied.
struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable, CaseIterable {
        case text, link, color, image, file
    }

    var id = UUID()
    var kind: Kind
    /// Text, link, colour code, or file paths (one per line).
    var text: String
    /// Rich text as copied (pasted back with its formatting).
    var rtf: Data?
    /// Images live next to the history file as <id>.png.
    var hasImage = false
    var imageSize: CGSize?
    /// Text read off an image (for search).
    var imageText: String?
    var appName: String?
    var bundleID: String?
    var date = Date()
    var pinned = false
    /// Looks like a card number or a token: dropped after a minute.
    var sensitive = false
    /// Taken with Shotleaf (kept even if never copied). Optional: older history has no such field.
    var screenshot: Bool?

    /// What search matches against.
    var searchable: String { [text, imageText ?? ""].joined(separator: "\n") }

    var fileURLs: [URL] { kind == .file ? text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) } : [] }
}

/// The clipboard's history, kept on this Mac only (Application Support/Shotleaf/Clipboard).
/// Polls the pasteboard's change count — the standard way; there's no notification.
/// Skips what password managers mark as concealed / transient, what the user's
/// excluded apps copy, and Shotleaf's own pastes.
@MainActor
@Observable
final class ClipboardHistory {
    private(set) var items: [ClipItem] = []
    /// No recording until then.
    var pausedUntil: Date?
    /// "Paste one by one": what ⇧⌘V pastes next, and how many there were.
    var queue: [UUID] = []
    var queueTotal = 0

    // Settings → Clipboard (read live, so the Settings window just writes UserDefaults).
    static let enabledKey = "clipboardEnabled", limitKey = "clipboardLimit", imageDaysKey = "clipboardImageDays", excludedKey = "clipboardExcluded"
    private var defaults: UserDefaults { .standard }
    var enabled: Bool { defaults.object(forKey: Self.enabledKey) as? Bool ?? true }
    var limit: Int { defaults.object(forKey: Self.limitKey) as? Int ?? 200 }
    var imageDays: Int { defaults.object(forKey: Self.imageDaysKey) as? Int ?? 30 }
    /// Bundle IDs whose copies are never kept (one per line in UserDefaults).
    var excludedApps: [String] {
        (defaults.string(forKey: Self.excludedKey) ?? Self.defaultExcluded.joined(separator: "\n")).split(separator: "\n").map(String.init)
    }

    static let defaultExcluded = ["com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop",
                                  "com.apple.keychainaccess", "com.apple.Passwords", "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal"]
    /// Marks Shotleaf's own writes so they aren't recorded twice.
    static let ownType = NSPasteboard.PasteboardType("dev.syvyj.shotleaf.own")
    private static let skipTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"), ownType,
    ]

    let folder: URL
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let recognizer: (any TextRecognizing)?

    init(folder: URL = ClipboardHistory.defaultFolder, recognizer: (any TextRecognizing)? = nil) {
        self.folder = folder
        self.recognizer = recognizer
        load()
    }

    static var defaultFolder: URL {
        AppInfo.supportFolder.appendingPathComponent("Clipboard", isDirectory: true)
    }

    func start() {
        guard timer == nil else { return }
        lastChange = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    var isPaused: Bool { pausedUntil.map { $0 > Date() } ?? false }

    // MARK: Recording

    private func poll() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        dropExpired()
        guard enabled, !isPaused else { return }
        let types = board.types ?? []
        guard !types.contains(where: Self.skipTypes.contains) else { return }
        let app = NSWorkspace.shared.frontmostApplication
        guard !excludedApps.contains(app?.bundleIdentifier ?? "") else { return }
        guard let (item, png) = Self.read(board) else { return }
        var new = item
        new.appName = app?.localizedName
        new.bundleID = app?.bundleIdentifier
        add(new, png: png)
    }

    /// What's on the pasteboard as an item (+ PNG for images); nil if nothing we keep.
    static func read(_ board: NSPasteboard) -> (ClipItem, Data?)? {
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return (ClipItem(kind: .file, text: urls.map(\.path).joined(separator: "\n")), nil)
        }
        if let string = board.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            var item = ClipItem(kind: kind(of: trimmed), text: string)
            item.rtf = board.data(forType: .rtf)
            item.sensitive = looksSensitive(trimmed)
            return (item, nil)
        }
        if let data = board.data(forType: .png) ?? board.data(forType: .tiff),
           let rep = NSBitmapImageRep(data: data), let png = rep.representation(using: .png, properties: [:]) {
            var item = ClipItem(kind: .image, text: "")
            item.hasImage = true
            item.imageSize = CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
            return (item, png)
        }
        return nil
    }

    static func kind(of text: String) -> ClipItem.Kind {
        if text.range(of: #"^#?[0-9A-Fa-f]{6}([0-9A-Fa-f]{2})?$"#, options: .regularExpression) != nil { return .color }
        if !text.contains(where: \.isWhitespace), let url = URL(string: text), let scheme = url.scheme?.lowercased(),
           ["http", "https"].contains(scheme), url.host != nil { return .link }
        return .text
    }

    /// A card number (passes Luhn) or a long secret-looking token.
    static func looksSensitive(_ text: String) -> Bool {
        let digits = text.filter(\.isNumber)
        let cardLike = text.allSatisfy { $0.isNumber || $0 == " " || $0 == "-" } && (13...19).contains(digits.count)
        if cardLike {
            let sum = digits.reversed().enumerated().reduce(0) { total, pair in
                var d = pair.element.wholeNumberValue ?? 0
                if pair.offset % 2 == 1 { d *= 2; if d > 9 { d -= 9 } }
                return total + d
            }
            if sum % 10 == 0 { return true }
        }
        let token = text.count >= 32 && !text.contains(where: \.isWhitespace)
            && text.contains(where: \.isNumber) && text.contains(where: \.isLetter) && !text.contains("/") && !text.contains(".")
        return token || text.hasPrefix("sk-") || text.hasPrefix("ghp_") || text.hasPrefix("xox")
    }

    func add(_ item: ClipItem, png: Data? = nil) {
        var item = item
        // The same text copied again moves up (keeping its pin).
        if !item.hasImage, let old = items.firstIndex(where: { !$0.hasImage && $0.text == item.text }) {
            item.pinned = items[old].pinned
            item.id = items[old].id
            items.remove(at: old)
        }
        if let png {
            try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
            try? png.write(to: imageURL(item))
        }
        items.insert(item, at: 0)
        trim()
        save()
        if let png, let recognizer { readText(of: item.id, png: png, recognizer) }
        if item.sensitive { // gone in a minute even if nothing else gets copied
            Task { try? await Task.sleep(for: .seconds(61)); self.dropExpired() }
        }
    }

    /// A new screenshot goes into the history straight away, so several can be
    /// picked and pasted together later. The id lets the editor update it.
    @discardableResult
    func addScreenshot(_ png: Data) -> UUID? {
        guard enabled, !isPaused, let rep = NSBitmapImageRep(data: png) else { return nil }
        var item = ClipItem(kind: .image, text: "")
        item.hasImage = true
        item.imageSize = CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
        item.screenshot = true
        item.appName = AppInfo.name
        item.bundleID = AppInfo.bundleID
        add(item, png: png)
        return item.id
    }

    /// The screenshot as edited (marks, crop, background) replaces the one captured.
    func updateImage(_ id: UUID, png: Data) {
        guard let i = items.firstIndex(where: { $0.id == id }), let rep = NSBitmapImageRep(data: png) else { return }
        try? png.write(to: imageURL(items[i]))
        items[i].imageSize = CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
        items[i].imageText = nil
        save()
        if let recognizer { readText(of: id, png: png, recognizer) }
    }

    private func readText(of id: UUID, png: Data, _ recognizer: any TextRecognizing) {
        Task {
            guard let rep = NSBitmapImageRep(data: png),
                  let text = try? await recognizer.recognizeText(in: ImagePayload(data: png, width: rep.pixelsWide, height: rep.pixelsHigh)),
                  let i = items.firstIndex(where: { $0.id == id }) else { return }
            items[i].imageText = text
            save()
        }
    }

    // MARK: Editing

    func togglePin(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        items[i].pinned.toggle()
        save()
    }

    func remove(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        try? FileManager.default.removeItem(at: imageURL(items[i]))
        items.remove(at: i)
        save()
    }

    /// Everything but the pinned.
    func clear() {
        for item in items where !item.pinned { try? FileManager.default.removeItem(at: imageURL(item)) }
        items.removeAll { !$0.pinned }
        save()
    }

    func imageURL(_ item: ClipItem) -> URL { folder.appendingPathComponent("\(item.id.uuidString).png") }

    func image(_ item: ClipItem) -> NSImage? { item.hasImage ? NSImage(contentsOf: imageURL(item)) : nil }

    // MARK: Search

    /// Pinned first, then the rest, newest first; every word of `query` must match.
    func search(_ query: String, kind: ClipItem.Kind? = nil) -> [ClipItem] {
        let words = query.lowercased().split(separator: " ").map(String.init)
        let found = items.filter { item in
            (kind == nil || item.kind == kind) && words.allSatisfy { item.searchable.lowercased().contains($0) }
        }
        return found.filter(\.pinned) + found.filter { !$0.pinned }
    }

    // MARK: Writing back

    /// Puts the item on the clipboard (marked as Shotleaf's, so it isn't recorded
    /// again). `plain` drops the formatting.
    func copy(_ item: ClipItem, plain: Bool = false, to board: NSPasteboard = .general) {
        board.clearContents()
        switch item.kind {
        case .image:
            if let data = try? Data(contentsOf: imageURL(item)) { board.setData(data, forType: .png) }
        case .file:
            board.writeObjects(item.fileURLs as [NSURL])
        default:
            board.setString(item.text, forType: .string)
            if !plain, let rtf = item.rtf { board.setData(rtf, forType: .rtf) }
        }
        board.setData(Data(), forType: Self.ownType)
        lastChange = board.changeCount
        // Used again: to the top.
        if let i = items.firstIndex(where: { $0.id == item.id }), i > 0 {
            var moved = items.remove(at: i)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    /// Several entries as one paste. Each image (and file) is its own pasteboard
    /// item — a PNG plus a named file, so apps that take several pictures or
    /// attachments get them all; the texts go in as one, a line each.
    func copyTogether(_ picked: [ClipItem], to board: NSPasteboard = .general) {
        let folder = FileManager.default.temporaryDirectory.appendingPathComponent("Shotleaf Paste/\(UUID().uuidString)", isDirectory: true)
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        var objects: [NSPasteboardItem] = []
        let text = picked.filter { $0.kind != .image && $0.kind != .file }.map(\.text).joined(separator: "\n")
        if !text.isEmpty {
            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            objects.append(item)
        }
        for (n, entry) in picked.filter({ $0.kind == .image }).enumerated() {
            guard let png = try? Data(contentsOf: imageURL(entry)) else { continue }
            let file = folder.appendingPathComponent(String(localized: "Screenshot") + " \(n + 1).png")
            try? png.write(to: file)
            let item = NSPasteboardItem()
            item.setData(png, forType: .png)
            item.setString(file.absoluteString, forType: .fileURL)
            objects.append(item)
        }
        for url in picked.flatMap(\.fileURLs) {
            let item = NSPasteboardItem()
            item.setString(url.absoluteString, forType: .fileURL)
            objects.append(item)
        }
        objects.forEach { $0.setData(Data(), forType: Self.ownType) }
        board.clearContents()
        board.writeObjects(objects)
        lastChange = board.changeCount
    }

    // MARK: Storage

    private var file: URL { folder.appendingPathComponent("history.json") }

    private func load() {
        guard let data = try? Data(contentsOf: file), let saved = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = saved
        dropExpired()
    }

    func save() {
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        try? JSONEncoder().encode(items).write(to: file, options: .atomic)
    }

    /// Over the limit, old images, and sensitive bits older than a minute go (never the pinned).
    private func trim() {
        let imageCutoff = Date().addingTimeInterval(-Double(imageDays) * 86_400)
        var kept: [ClipItem] = []
        var unpinned = 0
        for item in items {
            let tooOld = item.hasImage && item.date < imageCutoff
            let over = !item.pinned && unpinned >= limit
            if !item.pinned && (tooOld || over) {
                try? FileManager.default.removeItem(at: imageURL(item))
                continue
            }
            if !item.pinned { unpinned += 1 }
            kept.append(item)
        }
        items = kept
    }

    private func dropExpired() {
        let cutoff = Date().addingTimeInterval(-60)
        let before = items.count
        items.removeAll { $0.sensitive && !$0.pinned && $0.date < cutoff }
        trim()
        if items.count != before { save() }
    }
}
